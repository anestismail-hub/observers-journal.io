const LILA_ARROWS = { 10:13, 17:19, 20:23, 26:28, 30:32, 33:35, 37:39, 40:42, 44:48, 46:50, 51:54, 54:68, 63:66 };
const LILA_SNAKES = { 55:3, 12:4, 16:4, 24:9, 44:33, 58:52, 61:58, 67:62, 70:65, 72:51 };
let lilaPos = null, lilaRolls = 0, lilaArrows = 0, lilaSnakes = 0, lilaStarted = false;
const boardEl = document.getElementById('lilaBoard');

function initLilaBoard(){
  boardEl.innerHTML = '';
  for(let i = 1; i <= 72; i++){
    const s = LILA[i-1];
    const sq = document.createElement('div');
    sq.className = 'sq ' + (s ? s.c : '');
    sq.id = 'sq' + i;
    if(LILA_ARROWS[i]) sq.classList.add('arrow');
    if(LILA_SNAKES[i]) sq.classList.add('snake');
    if(i === 67 || i === 68) sq.classList.add('goal');
    sq.innerHTML = '<div class="num">' + i + '</div><div class="nm">' + (s ? s.n : '') + '</div>';
    (function(n){ sq.onclick = function(){ showSquareInfo(n); }; })(i);
    boardEl.appendChild(sq);
  }
  renderToken();
}

function renderToken(){
  document.querySelectorAll('.sq .token').forEach(function(t){ t.remove(); });
  if(lilaPos === null) return;
  const sq = document.getElementById('sq' + lilaPos);
  if(sq){
    const t = document.createElement('div');
    t.className = 'token';
    t.textContent = '◉';
    sq.appendChild(t);
  }
}

function showSquareInfo(i){
  const s = LILA[i-1];
  if(!s) return;
  const catNames = { plane: 'План', virtue: 'Добродетель', vice: 'Порок', realize: 'Осознание', goal: 'Цель' };
  document.getElementById('lilaInfo').innerHTML =
    '<h4>' + i + '. ' + s.n + ' <span class="cat ' + s.c + '">' + (catNames[s.c] || '') + '</span></h4>' +
    '<div class="skr">' + s.sk + '</div>' +
    '<p>' + s.d + '</p>' +
    '<p class="q">' + s.q + '</p>';
  playTone(660 + i*2, 0.12, 'sine', 0.02);
}

function rollDice(){
  const btn = document.getElementById('diceBtn');
  const face = document.getElementById('diceFace');
  btn.disabled = true;
  btn.classList.add('rolling');
  diceSnd();
  let ticks = 0;
  const iv = setInterval(function(){
    face.textContent = Math.floor(Math.random()*6) + 1;
    ticks++;
    if(ticks > 10){ clearInterval(iv); finishRoll(); }
  }, 85);

  function finishRoll(){
    btn.classList.remove('rolling');
    btn.disabled = false;
    const d = Math.floor(Math.random()*6) + 1;
    face.textContent = d;
    face.classList.add('pop');
    setTimeout(function(){ face.classList.remove('pop'); }, 350);
    playTone(880, 0.2, 'sine', 0.05);

    if(!lilaStarted){
      if(d === 6){
        lilaStarted = true;
        lilaPos = 6;
        lilaRolls++;
        document.getElementById('lilaPos').textContent = lilaPos;
        document.getElementById('lilaRolls').textContent = lilaRolls;
        logLila('<span class="highlight">✦ Вы выбросили 6 и вошли на клетку 6.</span>');
        showSquareInfo(6);
        renderToken();
      }else{
        logLila('Выброшено ' + d + '. Чтобы войти, нужно 6.');
      }
      return;
    }

    lilaRolls++;
    let newPos = Math.min(68, lilaPos + d);
    lilaPos = newPos;
    document.getElementById('lilaPos').textContent = lilaPos;
    document.getElementById('lilaRolls').textContent = lilaRolls;
    logLila('Выпало ' + d + '. Переход на ' + lilaPos + ' «' + (LILA[lilaPos-1] ? LILA[lilaPos-1].n : '') + '».');
    showSquareInfo(lilaPos);
    renderToken();

    if(LILA_ARROWS[lilaPos]){
      const to = LILA_ARROWS[lilaPos];
      lilaArrows++;
      document.getElementById('lilaArrows').textContent = lilaArrows;
      setTimeout(function(){
        lilaPos = to;
        document.getElementById('lilaPos').textContent = lilaPos;
        logLila('<span class="mint">⬆ Стрела! Подъём на ' + to + '.</span>');
        showSquareInfo(to);
        renderToken();
        chimeSnd();
      }, 700);
    }else if(LILA_SNAKES[lilaPos]){
      const to = LILA_SNAKES[lilaPos];
      lilaSnakes++;
      document.getElementById('lilaSnakes').textContent = lilaSnakes;
      setTimeout(function(){
        lilaPos = to;
        document.getElementById('lilaPos').textContent = lilaPos;
        logLila('<span class="danger">⬇ Змея! Спуск на ' + to + '.</span>');
        showSquareInfo(to);
        renderToken();
        playTone(220, 0.3, 'sine', 0.04);
      }, 700);
    }

    if(lilaPos === 68){
      setTimeout(function(){
        logLila('<span class="highlight">✧ Вы достигли клетки 68 — Космическое сознание.</span>');
        successSnd();
      }, 900);
    }
  }
}

