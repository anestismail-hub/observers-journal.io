function toggleSound(){
  soundEnabled = !soundEnabled;
  const b = document.getElementById('soundToggle');
  b.textContent = soundEnabled ? '✦' : '✧';
  b.classList.toggle('off', !soundEnabled);
  if(soundEnabled) chimeSnd();
}

function toggleAmbient(){
  const b = document.getElementById('ambientBtn');
  if(ambientEnabled){
    if(ambientNodes){
      try{ ambientNodes.forEach(function(n){ n.stop(); }); }catch(e){}
      ambientNodes = null;
    }
    ambientEnabled = false;
    b.classList.add('off');
  }else{
    initAudio();
    ambientNodes = [];
    [110, 164.81, 220, 277.18, 329.63].forEach(function(f, i){
      const o = audioCtx.createOscillator();
      const g = audioCtx.createGain();
      const l = audioCtx.createOscillator();
      const lg = audioCtx.createGain();
      o.type = i % 2 ? 'sine' : 'triangle';
      o.frequency.value = f;
      g.gain.value = 0.011 / (i*0.4 + 1);
      l.frequency.value = 0.08 + i*0.05;
      lg.gain.value = 0.006 / (i*0.3 + 1);
      l.connect(lg);
      lg.connect(g.gain);
      o.connect(g);
      g.connect(audioCtx.destination);
      o.start();
      l.start();
      ambientNodes.push(o, l);
    });
    ambientEnabled = true;
    b.classList.remove('off');
  }
}

/* ============ STARS CANVAS ============ */
(function(){
  const c = document.getElementById('stars');
  const x = c.getContext('2d');
  let s = [];
  let d = window.devicePixelRatio || 1;

  function resize(){
    c.width = innerWidth * d;
    c.height = innerHeight * d;
    c.style.width = innerWidth + 'px';
    c.style.height = innerHeight + 'px';
    x.scale(d, d);
    s = [];
    const n = Math.floor(innerWidth * innerHeight / 3200);
    for(let i = 0; i < n; i++){
      s.push({
        x: Math.random()*innerWidth,
        y: Math.random()*innerHeight,
        r: Math.random()*1.5 + 0.3,
        a: Math.random()*0.5 + 0.22,
        sp: Math.random()*0.0018 + 0.0006,
        ph: Math.random()*Math.PI*2,
        b: Math.random() > 0.93,
        big: Math.random() > 0.97
      });
    }
  }

  function draw(t){
    x.clearRect(0, 0, innerWidth, innerHeight);
    const bs = s.filter(function(p){ return p.big; });
    x.strokeStyle = 'rgba(212,165,116,.05)';
    x.lineWidth = 1;
    for(let i = 0; i < bs.length; i++){
      for(let j = i+1; j < bs.length; j++){
        const dx = bs[i].x - bs[j].x;
        const dy = bs[i].y - bs[j].y;
        const dd = Math.sqrt(dx*dx + dy*dy);
        if(dd < 150){
          x.beginPath();
          x.moveTo(bs[i].x, bs[i].y);
          x.lineTo(bs[j].x, bs[j].y);
          x.stroke();
        }
      }
    }
    for(let k = 0; k < s.length; k++){
      const p = s[k];
      const a = Math.max(0, Math.min(1, p.a + Math.sin(t*p.sp + p.ph) * 0.38));
      x.beginPath();
      x.arc(p.x, p.y, p.r, 0, Math.PI*2);
      x.fillStyle = p.b
        ? 'rgba(232,194,152,' + a + ')'
        : 'rgba(235,226,208,' + a + ')';
      x.fill();
      if(p.b){
        x.beginPath();
        x.arc(p.x, p.y, p.r*3.5, 0, Math.PI*2);
        x.fillStyle = 'rgba(127,184,168,' + (a*0.14) + ')';
        x.fill();
      }
    }
    requestAnimationFrame(draw);
  }

  resize();
  addEventListener('resize', resize);
  requestAnimationFrame(draw);
})();

