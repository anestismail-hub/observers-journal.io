function loopS(n){
  const st = SS[n], cfg = SC[n];
  if(!st.run || st.pau) return;
  const now = performance.now();
  const dt = (now - st.last) / 1000;
  st.last = now;
  st.el += dt;
  st.pe += dt;
  const ph = ['inh','hold','exh','he'];
  const du = [cfg.inh, cfg.hold, cfg.exh, cfg.he];
  let i = ph.indexOf(st.ph), d = du[i];
  while(d === 0){ i = (i + 1) % 4; st.ph = ph[i]; d = du[i]; st.pe = 0; }
  if(st.pe >= d){
    st.pe = 0;
    i = (i + 1) % 4;
    st.ph = ph[i];
    d = du[i];
    while(d === 0){ i = (i + 1) % 4; st.ph = ph[i]; d = du[i]; }
    phaseSnd();
  }
  const c = document.getElementById('core' + n);
  const h = document.getElementById('hint' + n);
  const tm = document.getElementById('timer' + n);
  h.textContent = cfg.ins[st.ph];
  let sc = 1;
  if(st.ph === 'inh') sc = 1 + (st.pe / d) * 0.8;
  else if(st.ph === 'exh') sc = 1.8 - (st.pe / d) * 0.8;
  else if(st.ph === 'hold') sc = 1.8;
  c.style.transform = 'scale(' + sc + ')';
  c.textContent = Math.max(0, Math.ceil(d - st.pe));
  tm.textContent = fmt(Math.max(0, cfg.dur - st.el));
  if(st.el >= cfg.dur){
    st.run = false;
    st.pau = false;
    document.getElementById('stage' + n).classList.remove('active');
    document.getElementById('btn' + n).textContent = '✓ Этап ' + n + ' завершён';
    document.getElementById('hint' + n).textContent = 'Благодарю. Свет наполняет вас.';
    document.getElementById('status' + n).textContent = 'Этап ' + n + ' завершён';
    document.getElementById('pause' + n).style.display = 'none';
    chimeSnd();
    if(n === 1) document.getElementById('status2').textContent = 'Готов к этапу 2';
    return;
  }
  st.raf = requestAnimationFrame(function(){ loopS(n); });
}

