const SHORT_IDS = [0, 1, 2, 3, 5, 6, 12, 13, 14, 15, 16, 21, 22, 23, 29, 37];
let mode = 'full';
let visibleChapters = [];
let currentChapter = 0;

function buildVisible(){
  visibleChapters = mode === 'full'
    ? BOOK_CHAPTERS.map(function(c){ return Object.assign({}, c); })
    : SHORT_IDS.map(function(i){ return Object.assign({}, BOOK_CHAPTERS[i]); });
  currentChapter = 0;
}

function openBook(){
  document.getElementById('bookCoverWrap').style.display = 'none';
  document.getElementById('bookReader').classList.add('open');
  buildVisible();
  renderChapter(0);
  pageSnd();
  document.getElementById('bookReader').scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function closeBook(){
  document.getElementById('bookReader').classList.remove('open');
  document.getElementById('bookCoverWrap').style.display = 'block';
  pageSnd();
}

function setMode(m){
  mode = m;
  document.getElementById('btnFull').classList.toggle('active', m === 'full');
  document.getElementById('btnShort').classList.toggle('active', m === 'short');
  buildVisible();
  renderChapter(0);
  pageSnd();
}

function renderChapterList(){
  const box = document.getElementById('chapterLinks');
  box.innerHTML = '';
  let lastPart = -1;
  visibleChapters.forEach(function(ch, i){
    if(ch.part !== lastPart){
      lastPart = ch.part;
      const p = BOOK_PARTS[ch.part];
      if(p){
        const h = document.createElement('div');
        h.className = 'ch-part';
        h.innerHTML = '<span class="part-label">' + p.label + '</span><span class="part-title">' + p.title + '</span>';
        box.appendChild(h);
      }
    }
    const el = document.createElement('div');
    el.className = 'ch-link' + (i === currentChapter ? ' active' : '');
    el.innerHTML = '<span class="ch-num">' + String(i + 1).padStart(2, '0') + '</span><span class="ch-name">' + ch.title + '</span><span class="ch-arrow">→</span>';
    el.onclick = function(){ goToChapter(i); };
    box.appendChild(el);
  });
}

function toggleChapters(){
  document.getElementById('chapterList').classList.toggle('open');
  playTone(500, 0.12, 'sine', 0.028);
}

function goToChapter(i){
  if(i < 0 || i >= visibleChapters.length) return;
  currentChapter = i;
  renderChapter(i);
  pageSnd();
  document.getElementById('chapterList').classList.remove('open');
}

function renderChapter(i){
  const ch = visibleChapters[i];
  const body = document.getElementById('readerBody');
  let html = '<div class="ch-head"><div class="ch-label">' + ch.sub + '</div><h3>' + ch.title + '</h3></div>';
  html += '<div class="epi">' + ch.epi + '</div>';
  html += '<div class="prayer-text">' + ch.intro + '</div>';
  ch.msgs.forEach(function(m){
    const isO = m.who === 'observer';
    html += '<div class="msg ' + (isO ? 'observer' : 'voice') + '"><div class="avatar">' + (isO ? 'О' : '✦') + '</div><div class="bubble"><span class="who">' + (isO ? 'Наблюдатель' : 'Голос') + '</span>' + m.text + '</div></div>';
  });
  if(ch.molitva){
    html += '<div class="molitva"><div class="molitva-title">' + ch.molitva.title + '</div>' + ch.molitva.text + '</div>';
  }
  html += '<div class="note">' + ch.note + '</div>';
  html += '<div class="practice"><strong>Практика записи</strong>' + ch.practice + '</div>';
  body.innerHTML = html;
  document.getElementById('readerCount').textContent = (i + 1) + ' / ' + visibleChapters.length;
  document.getElementById('prevBtn').disabled = (i === 0);
  document.getElementById('nextBtn').disabled = (i === visibleChapters.length - 1);
  document.getElementById('readerProgressFill').style.width = ((i + 1) / visibleChapters.length * 100) + '%';
  renderChapterList();
  body.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

function prevChapter(){ if(currentChapter > 0) goToChapter(currentChapter - 1); }
function nextChapter(){ if(currentChapter < visibleChapters.length - 1) goToChapter(currentChapter + 1); }

buildVisible();
renderChapterList();

