/* ============ JOURNAL ============ */
const J_KEY = 'observer_journal_v6';
let journalEntries = JSON.parse(localStorage.getItem(J_KEY) || '[]');

function renderJournal(){
  const list = document.getElementById('journalList');
  list.innerHTML = '';
  if(journalEntries.length === 0){
    list.innerHTML = '<p style="color:var(--faint);font-style:italic;text-align:center;">Пока нет записей.</p>';
    return;
  }
  const sorted = journalEntries.map(function(e, i){ return { e: e, i: i }; }).sort(function(a, b){ return b.e.ts - a.e.ts; });
  sorted.forEach(function(item){
    const e = item.e;
    const idx = item.i;
    const div = document.createElement('div');
    div.className = 'journal-entry';
    div.innerHTML = '<div class="entry-head"><span>' + e.date + '</span><div class="entry-actions"><button onclick="editJournal(' + idx + ')">Править</button><button onclick="deleteJournal(' + idx + ')">Удалить</button></div></div><div class="entry-text">' + e.text.replace(/</g, '&lt;').replace(/\n/g, '<br>') + '</div>';
    list.appendChild(div);
  });
}

function saveJournal(){
  const ta = document.getElementById('journalInput');
  const text = ta.value.trim();
  if(!text) return;
  const date = new Date().toISOString().slice(0, 10);
  journalEntries.push({ date: date, text: text, ts: Date.now() });
  localStorage.setItem(J_KEY, JSON.stringify(journalEntries));
  ta.value = '';
  renderJournal();
  chimeSnd();
}

function deleteJournal(i){
  if(confirm('Удалить запись?')){
    journalEntries.splice(i, 1);
    localStorage.setItem(J_KEY, JSON.stringify(journalEntries));
    renderJournal();
    playTone(300, 0.15, 'sine', 0.03);
  }
}

function editJournal(i){
  const e = journalEntries[i];
  const ta = document.getElementById('journalInput');
  ta.value = e.text;
  ta.focus();
  journalEntries.splice(i, 1);
  localStorage.setItem(J_KEY, JSON.stringify(journalEntries));
  renderJournal();
}

function clearJournalInput(){
  document.getElementById('journalInput').value = '';
}

renderJournal();

